String _normalise(String text) {
  final String lower = text.toLowerCase();
  final String letters = lower.replaceAll(RegExp(r'[^a-z]+'), ' ').trim();
  return ' $letters ';
}

/// A name (and its aliases) in the form [paddedHasWord] searches: lower case,
/// letters only, spaces at both ends. Work this out once per item, not once
/// per keyword.
String paddedName(String name, [Iterable<String> aliases = const <String>[]]) {
  return _normalise('$name ${aliases.join(' ')}');
}

/// [nameHasWord] for a name already prepared with [paddedName].
bool paddedHasWord(String padded, String keyword) => _hasWord(padded, keyword);

bool _hasWord(String padded, String keyword) {
  return padded.contains(' $keyword ') ||
      padded.contains(' ${keyword}s ') ||
      padded.contains(' ${keyword}es ');
}

/// True when [keyword] (a word or phrase) is in the item's name or one of its
/// aliases, as whole words ("oil" is not in "boiled"), allowing a plural.
bool nameHasWord(String name, Iterable<String> aliases, String keyword) {
  return _hasWord(_normalise('$name ${aliases.join(' ')}'), keyword);
}

final Map<String, FoodEnergy?> _lookups = <String, FoodEnergy?>{};

/// The table entry for an item, from its name and aliases. Null when nothing
/// matches. Answers are remembered, since the same names come up again and
/// again.
FoodEnergy? findFoodEnergy(
  String name, [
  Iterable<String> aliases = const <String>[],
]) {
  final String padded = _normalise('$name ${aliases.join(' ')}');
  if (_lookups.containsKey(padded)) {
    return _lookups[padded];
  }
  FoodEnergy? found;
  search:
  for (final FoodEnergy entry in kFoodEnergyTable) {
    for (final String keyword in entry.keywords) {
      if (_hasWord(padded, keyword)) {
        found = entry;
        break search;
      }
    }
  }
  if (_lookups.length > 4000) {
    _lookups.clear();
  }
  _lookups[padded] = found;
  return found;
}

/// The energy and nutrients of [quantity] [unit] of [food], or null when the
/// amount cannot be turned into grams or millilitres (a packet, a portion, a
/// piece whose weight is not known).
EnergyEstimate? estimateEnergy(FoodEnergy food, double quantity, Unit unit) {
  if (quantity <= 0) {
    return null;
  }
  switch (unit.family) {
    case UnitFamily.mass:
      final double? per = food.kcalPer100g ?? food.kcalPer100ml;
      if (per == null) {
        return null;
      }
      final double g = unit.convertTo(quantity, Unit.g);
      return _estimate(food, kcal: g / 100 * per, weightG: g, grams: g);
    case UnitFamily.volume:
      final double? per = food.kcalPer100ml ?? food.kcalPer100g;
      if (per == null) {
        return null;
      }
      final double ml = unit.convertTo(quantity, Unit.ml);
      // Nutrients are per 100 g, so a volume is first turned into a weight.
      final double? perG = food.kcalPer100g;
      final double? perMl = food.kcalPer100ml;
      final double density = (perG != null && perG > 0 && perMl != null)
          ? perMl / perG
          : 1;
      return _estimate(
        food,
        kcal: ml / 100 * per,
        weightG: ml * density,
        amount: ml,
      );
    case UnitFamily.pieces:
      return _fromPieces(food, quantity);
    case UnitFamily.dozen:
      return _fromPieces(food, quantity * 12);
    case UnitFamily.bunch:
      final double? perBunch = food.gramsPerBunch;
      final double? per = food.kcalPer100g;
      if (perBunch == null || per == null) {
        return null;
      }
      final double g = quantity * perBunch;
      return _estimate(food, kcal: g / 100 * per, weightG: g, grams: g);
    case UnitFamily.packet:
    case UnitFamily.portion:
      return null;
  }
}

EnergyEstimate? _fromPieces(FoodEnergy food, double pieces) {
  final double? perPiece = food.gramsPerPiece;
  final double? per = food.kcalPer100g;
  if (perPiece == null || per == null) {
    return null;
  }
  final double g = pieces * perPiece;
  return _estimate(food, kcal: g / 100 * per, weightG: g, grams: g);
}

EnergyEstimate _estimate(
  FoodEnergy food, {
  required double kcal,
  required double weightG,
  double? grams,
  double? amount,
}) {
  final double f = weightG / 100;
  return EnergyEstimate(
    kcal: kcal,
    grams: grams,
    amount: amount ?? weightG,
    protein: f * food.protein,
    carbs: f * food.carbs,
    fat: f * food.fat,
    fibre: f * food.fibre,
  );
}
