import '../../pantry/domain/unit.dart';

/// Food groups used for the energy estimate and the balance check.
enum FoodGroup {
  cereals('Grains'),
  pulses('Dals & pulses'),
  vegetables('Vegetables'),
  tubers('Roots & tubers'),
  fruits('Fruit'),
  dairy('Dairy'),
  meatEggs('Eggs & meat'),
  fats('Oils & ghee'),
  sugars('Sugar & sweets'),
  nutsSeeds('Nuts & seeds'),
  other('Spices & other');

  const FoodGroup(this.label);

  final String label;
}

/// Rough nutrition for one kind of food, per 100 g (or per 100 ml where given)
/// as it is bought: raw and uncooked, with typical piece and bunch weights.
///
/// These are ROUGH averages typed in from general knowledge of food
/// composition tables (ICMR-NIN "Indian Food Composition Tables" and USDA
/// FoodData Central are the places to check a value). Brands, varieties and
/// cooking change the real numbers, so the app always shows results as
/// estimates. A test checks that each entry's calories roughly agree with its
/// protein, carbohydrate, fat and fibre, which catches typing slips but not a
/// value that is wrong in the source.
final class FoodEnergy {
  const FoodEnergy(
    this.keywords,
    this.group, {
    this.kcalPer100g,
    this.kcalPer100ml,
    this.protein = 0,
    this.carbs = 0,
    this.fat = 0,
    this.fibre = 0,
    this.gramsPerPiece,
    this.gramsPerBunch,
  });

  /// Lower-case words or phrases that identify the food in an item name
  /// (English, Hindi and Telugu names).
  final List<String> keywords;
  final FoodGroup group;
  final double? kcalPer100g;
  final double? kcalPer100ml;

  /// Grams of protein, carbohydrate (fibre included), fat and fibre in 100 g.
  final double protein;
  final double carbs;
  final double fat;
  final double fibre;
  final double? gramsPerPiece;
  final double? gramsPerBunch;
}

/// The energy and nutrients of an amount of food. [grams] is null when the
/// weight is not known (a liquid, say).
final class EnergyEstimate {
  const EnergyEstimate({
    required this.kcal,
    this.grams,
    this.amount = 0,
    this.protein = 0,
    this.carbs = 0,
    this.fat = 0,
    this.fibre = 0,
  });

  final double kcal;
  final double? grams;

  /// How much food this is, in grams (millilitres for a liquid). Used to
  /// compare what was eaten with a plate guide.
  final double amount;

  /// Grams of each nutrient in this amount.
  final double protein;
  final double carbs;
  final double fat;
  final double fibre;
}

